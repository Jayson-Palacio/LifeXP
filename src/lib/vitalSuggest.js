export const COOK_RECIPES = [...PACK_RECIPES, ...CROCKPOT_RECIPES];

function mealSlot(hour) {
  if (hour < 10) return 'breakfast';
  if (hour < 15) return 'lunch';
  return 'dinner';
}

function sourceFromUrl(url) {
  try {
    const host = new URL(url).hostname.replace(/^www\./, '');
    if (host.includes('budgetbytes')) return 'Budget Bytes';
    if (host.includes('seriouseats')) return 'Serious Eats';
    if (host.includes('cookieandkate')) return 'Cookie and Kate';
    if (host.includes('simplyrecipes')) return 'Simply Recipes';
    if (host.includes('skinnytaste')) return 'Skinnytaste';
    if (host.includes('loveandlemons')) return 'Love and Lemons';
  } catch { /* ignore */ }
  return null;
}

function kickerFor(slot) {
  if (slot === 'breakfast') return 'Cook this morning';
  if (slot === 'lunch') return 'Cook for lunch';
  return 'Cook tonight';
}

function kitchenHay(kitchen) {
  return kitchen.map((row) => String(row.name || '').toLowerCase()).join(' | ');
}

function hitTags(recipe, hay) {
  return (recipe.tags || []).filter((tag) => hay.includes(tag));
}

function scoreRecipe(recipe, ctx) {
  const items = itemsFor(recipe);
  const kcal = items.reduce((sum, row) => sum + (Number(row.calories) || 0), 0);
  const protein = items.reduce((sum, row) => sum + (Number(row.protein_g) || 0), 0);
  let score = 0;
  if (recipe.meal === ctx.slot) score += 20;
  else if ((recipe.meals || []).includes(ctx.slot)) score += 16;
  else if (ctx.slot === 'dinner' && recipe.meal === 'lunch') score += 4;
  else score -= 8;
  score += hitTags(recipe, ctx.hay).length * 10;
  if (ctx.child) return recipe.kidOk ? score + 8 : score - 50;
  if (ctx.remainingKcal != null) {
    if (ctx.remainingKcal < -80) score += recipe.quiet ? 18 : -12;
    else {
      const target = Math.min(Math.max(ctx.remainingKcal, 280), 720);
      score += Math.max(0, 24 - Math.abs(kcal - target) / 28);
    }
    if (ctx.remainingProtein > 20) score += Math.min(12, protein / 4);
  }
  return score;
}

function whyFor(recipe, ctx, items) {
  if (ctx.child) return 'A normal meal.';
  const hits = hitTags(recipe, ctx.hay);
  if (ctx.remainingKcal != null && ctx.remainingKcal < -80 && recipe.quiet) {
    return hits.length
      ? `Quieter plate. Uses ${hits.slice(0, 2).join(' and ')}.`
      : 'Quieter plate — the day already ran long.';
  }
  if (hits.length) return `Uses ${hits.slice(0, 2).join(' and ')}.`;
  return '';
}

export function plateForRecipe(recipe, slot = 'dinner') {
  return formatIdea(recipe, { slot, hay: '', simple: true, child: false });
}

function formatIdea(recipe, ctx) {
  const items = itemsFor(recipe);
  const kcal = items.reduce((sum, row) => sum + (Number(row.calories) || 0), 0);
  const protein = items.reduce((sum, row) => sum + (Number(row.protein_g) || 0), 0);
  const url = recipe.saved
    ? safeHttpUrl(recipe.recipeUrl)
    : (allowedRecipeUrl(recipe.recipeUrl) ? recipe.recipeUrl : null);
  return {
    id: recipe.id,
    title: recipe.title,
    why: whyFor(recipe, ctx, items),
    notes: recipe.notes || '',
    ingredients: recipe.ingredients || [],
    recipeUrl: url,
    recipeSource: url ? (recipe.recipeSource || sourceFromUrl(url) || (recipe.saved ? 'Your recipe' : null)) : null,
    items,
    meal: ctx.slot === 'breakfast' || ctx.slot === 'lunch' ? ctx.slot : (recipe.meal || 'dinner'),
    kcal: Math.round(kcal),
    protein: Math.round(protein),
    saved: Boolean(recipe.saved),
    tags: recipe.tags || [],
  };
}

export function cookTonight({
  kitchen = [],
  remainingKcal = null,
  remainingProtein = null,
  child = false,
  hour = 18,
  slot: slotArg,
  simple = false,
} = {}) {
  const slot = slotArg || mealSlot(hour);
  const hay = kitchenHay(kitchen);
  const ctx = { slot, hay, remainingKcal, remainingProtein, child, simple };
  const pool = COOK_RECIPES.filter((recipe) => (child ? recipe.kidOk : true));
  const ranked = [...pool].sort((a, b) => scoreRecipe(b, ctx) - scoreRecipe(a, ctx));
  const packIdeas = ranked.slice(0, 18).map((recipe) => formatIdea(recipe, ctx));
  const savedIdeas = kitchen
    .filter(isKitchenRecipe)
    .filter((row) => {
      const meta = kitchenRecipeMeta(row);
      if (!meta.meal) return true;
      return meta.meal === slot;
    })
    .map((row) => ideaFromKitchen(row, ctx));
  const ideas = [];
  const seen = new Set();
  for (const idea of [...savedIdeas, ...packIdeas]) {
    const key = String(idea.title || '').toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    ideas.push(idea);
    if (ideas.length >= 20) break;
  }
  return {
    kicker: kickerFor(slot),
    slot,
    ideas,
  };
}

function cookSearchScore(hay, title, words) {
  let score = 0;
  for (const word of words) {
    if (title.includes(word)) score += 40;
    else if (hay.includes(word)) score += 8;
  }
  if (words.every((word) => title.includes(word))) score += 80;
  score += Math.max(0, 16 - title.split(/\s+/).length);
  return score;
}

export function searchCookRecipes(query, ctx = {}) {
  const q = String(query || '').trim().toLowerCase();
  if (q.length < 2) return [];
  const words = q.split(/\s+/).filter(Boolean);
  const slot = ctx.slot || 'lunch';
  const pack = COOK_RECIPES
    .map((recipe) => {
      if (ctx.child && !recipe.kidOk) return null;
      const title = String(recipe.title || '').toLowerCase();
      const hay = `${title} ${(recipe.ingredients || []).join(' ')} ${(recipe.tags || []).join(' ')}`.toLowerCase();
      if (!words.every((word) => hay.includes(word))) return null;
      return { recipe, score: cookSearchScore(hay, title, words) };
    })
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)
    .slice(0, 16)
    .map(({ recipe }) => formatIdea(recipe, { ...ctx, slot, hay: ctx.hay || '', simple: true }));

  const saved = (ctx.kitchen || [])
    .filter(isKitchenRecipe)
    .filter((row) => {
      const meta = kitchenRecipeMeta(row);
      const hay = `${row.name} ${meta.ingredients.join(' ')} ${meta.notes} ${(meta.tags || []).join(' ')}`.toLowerCase();
      return words.every((word) => hay.includes(word));
    })
    .slice(0, 6)
    .map((row) => ideaFromKitchen(row, { ...ctx, slot }));

  const seen = new Set();
  const out = [];
  for (const idea of [...saved, ...pack]) {
    const key = String(idea.title || '').toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(idea);
    if (out.length >= 12) break;
  }
  return out;
}

export function suggestNextPlate(args) {
  const cook = cookTonight(args);
  const idea = cook.ideas[0];
  if (!idea) return null;
  return {
    title: idea.title,
    body: idea.why,
    items: idea.items,
  };
}
